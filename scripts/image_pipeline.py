#!/usr/bin/env python3
"""Brand overlay + optimiser + quality check + manifests for assets/visuals/<slug>/.
Logo is the approved repo asset (assets/logo-mark.png) composited programmatically; it is never model-drawn.
Usage: python3 scripts/image_pipeline.py [slug ...]
Outputs per slug: hero.webp (1600x900) + hero-800.webp, og.webp->og.png (1200x630 PNG for social crawlers), diagram.svg (already built).
Manifests: data/seo/image_manifest.json, image_license_registry.json, image_page_mapping.json, image_quality_report.json
"""
import json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "visuals")
SPECS = os.path.join(ROOT, "data", "visuals", "specs")
SEO = os.path.join(ROOT, "data", "seo")
LOGO = os.path.join(ROOT, "assets", "logo-mark.png")
MAX_KB = {"hero.webp": 140, "hero-800.webp": 60, "og.png": 400}


def overlay(base_png, px, margin):
    im = Image.open(base_png).convert("RGB")
    lg = Image.open(LOGO).convert("RGBA").resize((px, px), Image.LANCZOS)
    mask = Image.new("L", (px, px), 0)
    from PIL import ImageDraw
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, px - 1, px - 1), radius=px // 5, fill=255)
    lg.putalpha(mask)
    im.paste(lg, (im.width - px - margin, margin), lg)
    return im


def process(spec):
    d = os.path.join(OUT, spec["slug"]); b = os.path.join(d, "base")
    hero = overlay(os.path.join(b, "hero.png"), 72, 36)
    hero.save(os.path.join(d, "hero.webp"), "WEBP", quality=80, method=6)
    hero.resize((800, 450), Image.LANCZOS).save(os.path.join(d, "hero-800.webp"), "WEBP", quality=78, method=6)
    og = overlay(os.path.join(b, "og.png"), 56, 28)
    og.save(os.path.join(d, "og.png"), "PNG", optimize=True)
    return d


def check(spec, d):
    issues, files = [], {}
    for name, (w, h) in {"hero.webp": (1600, 900), "hero-800.webp": (800, 450), "og.png": (1200, 630)}.items():
        p = os.path.join(d, name)
        if not os.path.exists(p): issues.append(f"missing {name}"); continue
        im = Image.open(p); kb = round(os.path.getsize(p) / 1024, 1)
        files[name] = dict(width=im.width, height=im.height, kb=kb)
        if im.size != (w, h): issues.append(f"{name} size {im.size} != {(w, h)}")
        if kb > MAX_KB[name]: issues.append(f"{name} {kb}KB over {MAX_KB[name]}KB budget")
    svg = open(os.path.join(d, "diagram.svg"), encoding="utf-8").read()
    if "<title" not in svg or "<desc" not in svg: issues.append("diagram.svg lacks title/desc")
    if len(spec.get("alt", "")) < 40: issues.append("alt text too short")
    return files, issues


def main(slugs):
    specs = [json.load(open(os.path.join(SPECS, f), encoding="utf-8")) for f in sorted(os.listdir(SPECS))]
    specs = [s for s in specs if not slugs or s["slug"] in slugs]
    manifest, lic, mapping, quality = [], [], [], []
    for s in specs:
        d = process(s); files, issues = check(s, d)
        rel = f"assets/visuals/{s['slug']}"
        manifest.append(dict(image_id=s["id"], page=s["page"], title=s["title"], keyword=s["keyword"], description=s["caption"],
            generation_method="deterministic_svg_pillow", provider="none (local scripts, no generative model)", path=rel,
            dimensions={k: f"{v['width']}x{v['height']}" for k, v in files.items()}, sizes_kb={k: v["kb"] for k, v in files.items()},
            logo_applied=True, logo_source="assets/logo-mark.png (approved asset, composited programmatically)", alt_text=s["alt"],
            quality="pass" if not issues else "fail", publication_status="pending_page_integration"))
        lic.append(dict(image_id=s["id"], licence="Original work generated by this repository's scripts; no third-party imagery",
            third_party_logos_used=False, note="Platform vendor logos (Snowflake, Google Cloud, Databricks, Apache Kafka) are NOT embedded: official logo files and brand-usage permission are not documented in the repo."))
        mapping.append(dict(image_id=s["id"], page=s["page"], roles=["hero", "og", "diagram"]))
        quality.append(dict(image_id=s["id"], issues=issues, files=files))
    os.makedirs(SEO, exist_ok=True)
    for name, data in (("image_manifest", manifest), ("image_license_registry", lic), ("image_page_mapping", mapping), ("image_quality_report", quality)):
        json.dump(data, open(os.path.join(SEO, name + ".json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    bad = [q for q in quality if q["issues"]]
    print(f"processed {len(specs)}; failing {len(bad)}")
    for q in bad: print(" ", q["image_id"], q["issues"])
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
